/** 返回补充检索词（空字符串表示没有） */
export function expandQuery(q) {
  const extra = new Set();
  for (const [re, add] of SYNONYMS) if (re.test(q)) for (const w of add.split(" ")) if (!q.includes(w)) extra.add(w);
  return [...extra].join(" ");
}
